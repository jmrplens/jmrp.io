/**
 * Schema.org range guard
 *
 * The JSON-LD builders are typed with `schema-dts` and `satisfies`, checked
 * by `astro check`. That gate is blind to one shape: a node that carries an
 * `@id` and reaches a property through a variable is structurally an
 * `IdReference` (`{ "@id": string }`), so TypeScript accepts an `ItemList`
 * or a `Service` inside `hasPart` (range: CreativeWork) as long as it has an
 * `@id`. That is exactly how GEO audit #10's M2 was built, and the
 * Schema Markup Validator reported it as a severe error (GEO audit #11, B10).
 *
 * This checks the OUTPUT instead: every JSON-LD block of every built page,
 * with `@graph` and nested nodes flattened. For each property whose value is
 * a node (typed inline, or a bare `{"@id"}` reference resolved to the type
 * that node has on the same page, else anywhere in the build), one of the
 * value's types, or a supertype of it, must be in the property's schema.org
 * `rangeIncludes`. A `Role` is accepted anywhere, as the validators do.
 *
 * Deliberately NOT failures, reported as warnings:
 *
 *   - literal values (strings, numbers, dates, `@value` objects): the
 *     validators accept a Text fallback for any property;
 *   - properties schema.org does not define, and properties used outside
 *     their `domainIncludes` (the project states `codeRepository` and
 *     `programmingLanguage` on `SoftwareApplication` on purpose);
 *   - superseded properties, and references that resolve to no typed node.
 *
 * The vocabulary is pinned in `schema-vocabulary.json` (generated by
 * `generate-schema-vocabulary.mjs`), so the check is offline and gives the
 * same answer on every run.
 *
 * Run manually: `node scripts/ci/check-schema-ranges.mjs [distDir] [--verbose]`
 * Wired into `pnpm verify` (dist phase) and the CI `schema-validation` job.
 *
 * Exit codes: 0 no range violation · 1 range violations found (listed) ·
 * 2 the guard itself could not run (bad argument, unreadable build or
 * vocabulary).
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { VOCABULARY_PATH } from "./generate-schema-vocabulary.mjs";

/**
 * `schema:Thing` / `https://schema.org/Thing` / `Thing` -> `Thing`.
 *
 * @param {string} type - A `@type` value as written.
 * @returns {string} The bare term name.
 */
function bare(type) {
  return type.replace(/^(?:schema:|https?:\/\/schema\.org\/)/, "");
}

/**
 * A node's `@type` values, bare.
 *
 * @param {Record<string, unknown>} node - A JSON-LD node.
 * @returns {string[]} Its types; empty when it declares none.
 */
function typesOf(node) {
  return [node["@type"] ?? []]
    .flat()
    .filter((t) => typeof t === "string")
    .map(bare);
}

/**
 * Wraps the compact vocabulary with subclass lookups.
 *
 * @param {{release?: string, classes: Record<string, string[]>,
 *   properties: Record<string, {range: string[], domain: string[],
 *   supersededBy?: string[]}>}} raw - The parsed vocabulary file.
 * @returns {{release: string, isA: (type: string, cls: string) => boolean,
 *   knowsType: (type: string) => boolean, property: (name: string) =>
 *   {range: string[], domain: string[], supersededBy?: string[]} |
 *   undefined}} Lookups.
 */
export function createVocabulary(raw) {
  /** @type {Map<string, Set<string>>} */
  const ancestors = new Map();
  /**
   * The class and every class above it.
   *
   * @param {string} type - A class name.
   * @returns {Set<string>} The class and its ancestors.
   */
  const lineage = (type) => {
    const known = ancestors.get(type);
    if (known) return known;
    const out = new Set([type]);
    ancestors.set(type, out); // guards against a cycle in the source data
    for (const parent of raw.classes[type] ?? [])
      for (const a of lineage(parent)) out.add(a);
    return out;
  };
  return {
    release: raw.release ?? "unknown",
    isA: (type, cls) => lineage(type).has(cls),
    knowsType: (type) => Object.hasOwn(raw.classes, type),
    property: (name) =>
      Object.hasOwn(raw.properties, name) ? raw.properties[name] : undefined,
  };
}

/**
 * Reads the pinned vocabulary.
 *
 * @param {string} [file] - Override for tests.
 * @returns {ReturnType<typeof createVocabulary>} Lookups.
 */
export function loadVocabulary(file = VOCABULARY_PATH) {
  return createVocabulary(JSON.parse(fs.readFileSync(file, "utf8")));
}

/**
 * A `<script type="application/ld+json">` element and its body. A pattern,
 * not a DOM parse (15x slower over the whole build): every block is written
 * through `safeJsonLd()`, which escapes `<`, so a body can never contain
 * `</script>`, and the attribute is matched wherever the minifier put it.
 */
const JSON_LD_SCRIPT =
  /<script\b[^>]*\btype=["']?application\/ld\+json["']?[^>]*>([\s\S]*?)<\/script\s*>/gi;

/**
 * The JSON-LD blocks of a page, parsed.
 *
 * @param {string} html - The page source.
 * @returns {{blocks: unknown[], errors: string[]}} Parsed blocks, and a
 *   message per block that is not valid JSON.
 */
export function jsonLdBlocks(html) {
  /** @type {unknown[]} */
  const blocks = [];
  /** @type {string[]} */
  const errors = [];
  let i = 0;
  for (const [, body] of html.matchAll(JSON_LD_SCRIPT)) {
    i++;
    try {
      blocks.push(JSON.parse(body));
    } catch (error) {
      errors.push(`JSON-LD block ${i} is not valid JSON: ${error.message}`);
    }
  }
  return { blocks, errors };
}

/**
 * Calls `fn` on every object node under `value`, depth first.
 *
 * @param {unknown} value - A parsed JSON-LD block, or any part of one.
 * @param {(node: Record<string, unknown>) => void} fn - The visitor.
 * @returns {void}
 */
function walk(value, fn) {
  if (Array.isArray(value)) {
    for (const item of value) walk(item, fn);
  } else if (value && typeof value === "object") {
    fn(/** @type {Record<string, unknown>} */ (value));
    for (const child of Object.values(value)) walk(child, fn);
  }
}

/**
 * Every `@id` declared with a `@type`, mapped to all the types it is given.
 *
 * @param {unknown[]} blocks - Parsed JSON-LD.
 * @param {Map<string, Set<string>>} [into] - Map to add to.
 * @returns {Map<string, Set<string>>} `@id` -> types.
 */
export function typedIds(blocks, into = new Map()) {
  walk(blocks, (node) => {
    const id = node["@id"];
    const types = typesOf(node);
    if (typeof id !== "string" || types.length === 0) return;
    const known = into.get(id) ?? new Set();
    for (const t of types) known.add(t);
    into.set(id, known);
  });
  return into;
}

/**
 * @typedef {{file: string, blocks: unknown[]}} Page
 * @typedef {{key: string, files: string[]}} Finding
 */

/**
 * Adds `file` under `key`.
 *
 * @param {Map<string, Set<string>>} map - Findings by key.
 * @param {string} key - What was found.
 * @param {string} file - Where.
 * @returns {void}
 */
function note(map, key, file) {
  const files = map.get(key) ?? new Set();
  files.add(file);
  map.set(key, files);
}

/**
 * Findings map -> sorted list, most widespread first.
 *
 * @param {Map<string, Set<string>>} map - Findings by key.
 * @returns {Finding[]} The findings.
 */
function listed(map) {
  return [...map]
    .map(([key, files]) => ({
      key,
      files: [...files].sort((a, b) => a.localeCompare(b)),
    }))
    .sort(
      (a, b) => b.files.length - a.files.length || a.key.localeCompare(b.key),
    );
}

/**
 * The types a property value stands for: its own `@type`, or the types of the
 * node a bare `{"@id"}` reference names (on the same page first, then
 * anywhere in the build).
 *
 * @param {unknown} item - One value of a property.
 * @param {Map<string, Set<string>>} pageIds - Typed `@id`s of this page.
 * @param {Map<string, Set<string>>} siteIds - Typed `@id`s of the build.
 * @returns {string[] | null} The types; empty for a literal (a Text fallback
 *   the validators accept anywhere) or an untyped value; null for a
 *   reference to no typed node.
 */
function valueTypes(item, pageIds, siteIds) {
  if (item === null || typeof item !== "object" || "@value" in item) return [];
  const own = typesOf(/** @type {Record<string, unknown>} */ (item));
  const id = item["@id"];
  if (own.length > 0 || typeof id !== "string") return own;
  const target = pageIds.get(id) ?? siteIds.get(id);
  return target ? [...target] : null;
}

/**
 * @typedef {{vocabulary: ReturnType<typeof createVocabulary>,
 *   pageIds: Map<string, Set<string>>, siteIds: Map<string, Set<string>>,
 *   file: string, violations: Map<string, Set<string>>,
 *   warnings: Record<string, Map<string, Set<string>>>}} NodeContext
 */

/**
 * Checks one typed node's properties, recording what it finds.
 *
 * @param {Record<string, unknown>} node - The node.
 * @param {string[]} own - Its types.
 * @param {NodeContext} ctx - Lookups and the findings to add to.
 * @returns {number} How many node values were checked against a range.
 */
function checkNode(node, own, ctx) {
  const { vocabulary, warnings, file } = ctx;
  const where = own.join("+");
  let checked = 0;
  for (const t of own)
    if (!vocabulary.knowsType(t))
      note(warnings.unknownType, `@type ${t}`, file);
  for (const [key, value] of Object.entries(node)) {
    if (key.startsWith("@")) continue;
    const property = vocabulary.property(key);
    if (!property) {
      note(warnings.unknownProperty, `${where}.${key}`, file);
      continue;
    }
    const { range, domain, supersededBy } = property;
    if (
      domain.length > 0 &&
      own.every((t) => domain.every((d) => !vocabulary.isA(t, d)))
    )
      note(
        warnings.outsideDomain,
        `${where}.${key} (domain ${domain.join("|")})`,
        file,
      );
    if (supersededBy)
      note(
        warnings.superseded,
        `${where}.${key} -> ${supersededBy.join("|")}`,
        file,
      );
    if (range.length === 0) continue;
    for (const item of [value].flat(Infinity)) {
      const types = valueTypes(item, ctx.pageIds, ctx.siteIds);
      if (types === null) {
        note(
          warnings.unresolvedReference,
          `${where}.${key} -> ${item["@id"]}`,
          file,
        );
        continue;
      }
      if (types.length === 0) continue;
      checked++;
      const fits = types.some(
        (t) =>
          vocabulary.isA(t, "Role") || range.some((r) => vocabulary.isA(t, r)),
      );
      if (!fits)
        note(
          ctx.violations,
          `${where}.${key} = ${types.join("+")} (expected ${range.join("|")})`,
          file,
        );
    }
  }
  return checked;
}

/**
 * Checks the object values of every typed node against `rangeIncludes`.
 *
 * @param {Page[]} pages - Every page's parsed JSON-LD.
 * @param {ReturnType<typeof createVocabulary>} vocabulary - Lookups.
 * @returns {{violations: Finding[], warnings: Record<string, Finding[]>,
 *   checked: number}} Range violations (failures), warnings by kind, and how
 *   many node values were checked.
 */
export function checkRanges(pages, vocabulary) {
  const siteIds = new Map();
  for (const page of pages) typedIds(page.blocks, siteIds);

  const violations = new Map();
  const warnings = {
    unknownType: new Map(),
    unknownProperty: new Map(),
    outsideDomain: new Map(),
    superseded: new Map(),
    unresolvedReference: new Map(),
  };
  let checked = 0;

  for (const page of pages) {
    /** @type {NodeContext} */
    const ctx = {
      vocabulary,
      pageIds: typedIds(page.blocks),
      siteIds,
      file: page.file,
      violations,
      warnings,
    };
    walk(page.blocks, (node) => {
      const own = typesOf(node);
      if (own.length > 0) checked += checkNode(node, own, ctx);
    });
  }

  return {
    violations: listed(violations),
    warnings: Object.fromEntries(
      Object.entries(warnings).map(([kind, map]) => [kind, listed(map)]),
    ),
    checked,
  };
}

/**
 * Walks a directory tree collecting `.html` files.
 *
 * @param {string} root - Directory to walk.
 * @returns {string[]} Absolute file paths, sorted.
 */
function htmlFiles(root) {
  /** @type {string[]} */
  const out = [];
  for (const entry of fs.readdirSync(root, { withFileTypes: true })) {
    const full = path.join(root, entry.name);
    if (entry.isDirectory()) out.push(...htmlFiles(full));
    else if (entry.name.endsWith(".html")) out.push(full);
  }
  return out.sort((a, b) => a.localeCompare(b));
}

/**
 * Reads every built page's JSON-LD.
 *
 * @param {string} distDir - The built site.
 * @returns {{pages: Page[], parseErrors: Finding[]}} The pages, and any
 *   block that is not valid JSON (a failure: nothing downstream can read it).
 */
export function readDist(distDir) {
  /** @type {Page[]} */
  const pages = [];
  const parseErrors = new Map();
  for (const file of htmlFiles(distDir)) {
    const rel = path.relative(distDir, file);
    const { blocks, errors } = jsonLdBlocks(fs.readFileSync(file, "utf8"));
    for (const error of errors) note(parseErrors, error, rel);
    pages.push({ file: rel, blocks });
  }
  return { pages, parseErrors: listed(parseErrors) };
}

/** Headings for the warning kinds, in print order. */
const WARNING_TITLES = {
  unknownType: "types schema.org does not define",
  unknownProperty: "properties schema.org does not define",
  outsideDomain: "properties outside their domainIncludes",
  superseded: "superseded properties",
  unresolvedReference: "references to no typed node",
};

/**
 * Prints one group of findings.
 *
 * @param {Finding[]} findings - What to print.
 * @param {boolean} verbose - Every file, or the first one.
 * @param {(line: string) => void} print - console.log or console.error.
 * @returns {void}
 */
function printFindings(findings, verbose, print) {
  for (const { key, files } of findings) {
    const where = verbose ? files.join(" ") : `e.g. ${files[0]}`;
    print(
      `    ${String(files.length).padStart(3)} page(s)  ${key}  | ${where}`,
    );
  }
}

/**
 * CLI entry: checks the given build and sets the exit code.
 *
 * @param {string[]} argv - `[distDir] [--verbose]`.
 * @returns {void}
 * @throws {Error} When the argument is not a directory holding a built site.
 */
function main(argv) {
  const verbose = argv.includes("--verbose");
  const distArg = argv.find((a) => !a.startsWith("--")) ?? "dist";
  const resolved = path.resolve(process.cwd(), distArg);
  const isDirectory =
    fs.existsSync(resolved) && fs.statSync(resolved).isDirectory(); // NOSONAR: this IS the validation S8707 asks for, on the canonical path
  if (!isDirectory)
    throw new Error(`${distArg} (${resolved}) is not an existing directory`);
  // `dist` is a symlink to the live colour: resolve it once.
  const distDir = fs.realpathSync(resolved);
  if (!fs.existsSync(path.join(distDir, "index.html")))
    throw new Error(
      `${distArg} (${resolved}) holds no index.html; this guard reads built ` +
        `site output, and refuses to walk a directory that is not one`,
    );
  const vocabulary = loadVocabulary();
  const { pages, parseErrors } = readDist(distDir);
  const { violations, warnings, checked } = checkRanges(pages, vocabulary);

  const warningCount = Object.values(warnings).reduce(
    (n, list) => n + list.length,
    0,
  );
  if (warningCount > 0) {
    console.log(
      `ℹ️  ${warningCount} distinct warning(s), not failures (--verbose lists every page):`,
    );
    for (const [kind, title] of Object.entries(WARNING_TITLES)) {
      if (warnings[kind].length === 0) continue;
      console.log(`  ${title}:`);
      printFindings(warnings[kind], verbose, console.log);
    }
  }

  if (violations.length === 0 && parseErrors.length === 0) {
    console.log(
      `✅ Schema.org ranges hold in ${distArg}: ${pages.length} pages, ` +
        `${checked} node values checked against schema.org ${vocabulary.release}.`,
    );
    return;
  }
  if (parseErrors.length > 0) {
    console.error(`❌ Unreadable JSON-LD in ${distArg}:`);
    printFindings(parseErrors, true, console.error);
  }
  if (violations.length > 0) {
    console.error(
      `❌ Schema.org range violations in ${distArg} (schema.org ` +
        `${vocabulary.release}): ${violations.length} distinct, on ` +
        `${new Set(violations.flatMap((v) => v.files)).size} page(s):`,
    );
    printFindings(violations, true, console.error);
    console.error(
      "\n  Each value's type (or a supertype) must be in the property's\n" +
        "  rangeIncludes. Move the node to a property whose range accepts it\n" +
        "  (mainEntity takes any Thing), or change its type. schema-dts cannot\n" +
        "  see this when the node carries an @id. See GEO audit #11, B10.\n",
    );
  }
  process.exitCode = 1;
}

const invokedDirectly =
  process.argv[1] !== undefined &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (invokedDirectly) {
  try {
    main(process.argv.slice(2));
  } catch (error) {
    // Exit 2, never 1: a guard that could not run must not read as a finding.
    console.error("❌ check-schema-ranges could not run:", error);
    process.exitCode = 2;
  }
}
