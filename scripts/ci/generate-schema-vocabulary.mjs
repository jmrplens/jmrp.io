/**
 * Generates `scripts/ci/schema-vocabulary.json`, the pinned schema.org
 * vocabulary that `check-schema-ranges.mjs` checks the built JSON-LD against.
 *
 * The check runs offline and must give the same answer every time, so it
 * never downloads the vocabulary itself: this script compacts one release
 * into the few relations the check needs (each class's direct superclasses,
 * each property's `rangeIncludes`, `domainIncludes` and `supersededBy`) and
 * that file is committed. Updating it is a deliberate, reviewable change:
 *
 *   curl -4 -sSfL -o /tmp/schemaorg-current-https.jsonld \
 *     https://schema.org/version/30.1/schemaorg-current-https.jsonld
 *   node scripts/ci/generate-schema-vocabulary.mjs --release 30.1 \
 *     /tmp/schemaorg-current-https.jsonld
 *
 * (`https://schema.org/version/latest/` redirects to the newest release;
 * read its number off https://schema.org/docs/releases.html and pass it as
 * `--release`, so the file records which release it is.) The "current"
 * file holds the core vocabulary plus the pending and hosted extensions,
 * which is what the Schema Markup Validator accepts; the attic is left out.
 *
 * Output is deterministic: keys and lists sorted, one class or property per
 * line, so a release bump diffs as the terms that changed.
 */

// cspell:ignore schemaorg rdfs rxcui EIDR Checkin
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

/** Where the check reads the vocabulary from. */
export const VOCABULARY_PATH = fileURLToPath(
  new URL("schema-vocabulary.json", import.meta.url),
);

/**
 * `schema:Thing` / `https://schema.org/Thing` -> `Thing`; anything outside
 * the schema.org namespace -> null.
 *
 * @param {unknown} id - An `@id` from the vocabulary graph.
 * @returns {string | null} The bare term name.
 */
function termName(id) {
  if (typeof id !== "string") return null;
  const match = /^(?:schema:|https?:\/\/schema\.org\/)(.+)$/.exec(id);
  return match ? match[1] : null;
}

/**
 * Code-point order, the same on every machine and locale, so a regenerated
 * file diffs only where schema.org changed.
 *
 * @param {string} a - One name.
 * @param {string} b - The other.
 * @returns {number} Negative, zero or positive, as `sort` expects.
 */
function byCodePoint(a, b) {
  if (a === b) return 0;
  return a < b ? -1 : 1;
}

/**
 * The bare schema.org names referenced by a relation (`{"@id"}` or a list
 * of them), sorted.
 *
 * @param {unknown} value - The relation's value.
 * @returns {string[]} Referenced term names.
 */
function names(value) {
  if (value === undefined || value === null) return [];
  return [value]
    .flat()
    .map((v) => termName(v?.["@id"]))
    .filter((n) => n !== null)
    .sort(byCodePoint);
}

/**
 * Compacts a schema.org JSON-LD release graph to what the range check needs.
 *
 * @param {Record<string, unknown>[]} graph - The release's `@graph`.
 * @returns {{classes: Record<string, string[]>, properties: Record<string,
 *   {range: string[], domain: string[], supersededBy?: string[]}>}} Direct
 *   superclasses per class, and range/domain per property.
 */
export function compactVocabulary(graph) {
  /** @type {Record<string, string[]>} */
  const classes = {};
  /** @type {Record<string, {range: string[], domain: string[], supersededBy?: string[]}>} */
  const properties = {};
  for (const node of graph) {
    const name = termName(node["@id"]);
    if (name === null) continue;
    const types = new Set([node["@type"]].flat());
    if (types.has("rdfs:Class") || types.has("schema:DataType")) {
      classes[name] = names(node["rdfs:subClassOf"]);
    }
    if (types.has("rdf:Property")) {
      const entry = {
        range: names(node["schema:rangeIncludes"]),
        domain: names(node["schema:domainIncludes"]),
      };
      const supersededBy = names(node["schema:supersededBy"]);
      if (supersededBy.length > 0) entry.supersededBy = supersededBy;
      properties[name] = entry;
    }
  }
  return { classes, properties };
}

/**
 * Serializes the vocabulary one term per line, keys sorted.
 *
 * @param {{release: string, source: string, sha256: string}} meta - Where
 *   the vocabulary came from.
 * @param {ReturnType<typeof compactVocabulary>} vocabulary - The terms.
 * @returns {string} The file contents.
 */
export function serializeVocabulary(meta, vocabulary) {
  const block = (record) =>
    Object.keys(record)
      .sort(byCodePoint)
      .map((k) => `    ${JSON.stringify(k)}: ${JSON.stringify(record[k])}`)
      .join(",\n");
  // The note carries CSpell's directive: JSON has no comments, and CSpell
  // reads directives anywhere in the text. The term names are schema.org's
  // (rxcui, EIDR, Checkin...), not project prose.
  const note =
    "Generated by scripts/ci/generate-schema-vocabulary.mjs; do not edit by" +
    " hand. schema.org term names, not prose: cspell:disable";
  return (
    "{\n" +
    `  "//": ${JSON.stringify(note)},\n` +
    `  "release": ${JSON.stringify(meta.release)},\n` +
    `  "source": ${JSON.stringify(meta.source)},\n` +
    `  "sha256": ${JSON.stringify(meta.sha256)},\n` +
    `  "classes": {\n${block(vocabulary.classes)}\n  },\n` +
    `  "properties": {\n${block(vocabulary.properties)}\n  }\n` +
    "}\n"
  );
}

/**
 * CLI entry.
 *
 * @param {string[]} argv - `--release <n> <file>`.
 * @returns {void}
 * @throws {Error} On a missing argument or a file that is not a release.
 */
function main(argv) {
  const releaseAt = argv.indexOf("--release");
  const release = releaseAt === -1 ? undefined : argv[releaseAt + 1];
  const file = argv.find(
    (arg, i) => !arg.startsWith("--") && i !== releaseAt + 1,
  );
  if (!release || !/^\d+\.\d+$/.test(release) || !file) {
    throw new Error(
      "usage: generate-schema-vocabulary.mjs --release <N.N> <schemaorg-current-https.jsonld>",
    );
  }
  const raw = fs.readFileSync(path.resolve(file));
  const graph = JSON.parse(raw.toString("utf8"))["@graph"];
  if (!Array.isArray(graph)) throw new Error(`${file} has no @graph`);
  const vocabulary = compactVocabulary(graph);
  for (const required of ["Thing", "CreativeWork", "hasPart"]) {
    if (!(required in vocabulary.classes || required in vocabulary.properties))
      throw new Error(`${file} does not define ${required}: not a release?`);
  }
  const meta = {
    release,
    source: `https://schema.org/version/${release}/schemaorg-current-https.jsonld`,
    sha256: crypto.createHash("sha256").update(raw).digest("hex"),
  };
  fs.writeFileSync(VOCABULARY_PATH, serializeVocabulary(meta, vocabulary));
  console.log(
    `Wrote ${path.relative(process.cwd(), VOCABULARY_PATH)}: schema.org ` +
      `${release}, ${Object.keys(vocabulary.classes).length} classes, ` +
      `${Object.keys(vocabulary.properties).length} properties.`,
  );
}

const invokedDirectly =
  process.argv[1] !== undefined &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (invokedDirectly) {
  try {
    main(process.argv.slice(2));
  } catch (error) {
    console.error("❌ generate-schema-vocabulary:", error);
    process.exitCode = 2;
  }
}
