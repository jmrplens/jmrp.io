#!/usr/bin/env node
/**
 * Canonical project list generator.
 *
 * Writes `public/identity/projects.json` from `src/content/profile/projects.yaml`,
 * the same file /projects/ renders from, so the list exists once and is read
 * everywhere else.
 *
 * ── Why this exists ──────────────────────────────────────────────────────
 * The documentation hub on jmrplens.github.io kept its own copy of the same
 * projects in `src/data/site.ts`, and the copy drifted exactly as copies do:
 * two projects shipped and were listed here but not there, so their pages were
 * missing from that host's sitemap and llms.txt until someone noticed. This is
 * the same fix the `#person` entity already has, for the same reason: publish
 * one artifact, have the consumer fetch it at build time, and let a failed
 * fetch fail the build rather than ship a stale list.
 *
 * ── Why a committed file, and why not JSON-LD ────────────────────────────
 * Committed for the same reason `person.jsonld` is: consumer builds run on CI
 * runners and read it from raw.githubusercontent, never through this server's
 * Cloudflare / CrowdSec / MikroTik stack, where a blocked runner IP would
 * silently degrade them to a stale copy. Both paths serve the same bytes:
 *
 *   crawlers / humans → https://jmrp.io/identity/projects.json
 *   consumer builds   → https://raw.githubusercontent.com/jmrplens/jmrp.io/
 *                       main/public/identity/projects.json
 *
 * Plain JSON rather than JSON-LD, unlike `person.jsonld`, and the difference is
 * not cosmetic: that document IS an entity, spliced verbatim into other graphs
 * under one `@id`. This one is a DATA FEED the consumer builds its own nodes
 * from, and it carries fields with no schema.org meaning (`kicker`). Dressing
 * it as JSON-LD would claim a semantics it does not have.
 *
 * ── What consumers should do with it ─────────────────────────────────────
 * Filter. The list describes every project, including archived ones and those
 * whose documentation is just a README anchor. A consumer that publishes
 * documentation for a subset takes the subset: the hub keeps the entries whose
 * `docs` live on its own host, which is what decides membership there.
 *
 * Usage:
 *   node scripts/ci/build-projects.mjs            # write
 *   node scripts/ci/build-projects.mjs --check    # verify it matches the YAML
 *
 * @module
 */

import fs from "node:fs";
import path from "node:path";
import process from "node:process";

import { load as parseYaml } from "js-yaml";

const ROOT = process.cwd();
const SOURCE = path.join(ROOT, "src/content/profile/projects.yaml");
const TARGET = path.join(ROOT, "public/identity/projects.json");

/**
 * SPDX id to canonical license URL, read from the one table the site reads.
 *
 * A .mjs script cannot import a .ts module, which is what used to justify a
 * second copy here. It can read JSON, so there is one table and no copy to
 * keep in step. `src/data/knows-about-wikidata.json` is shared the same way.
 */
const LICENSE_URLS = JSON.parse(
  fs.readFileSync(path.join(ROOT, "src/data/license-urls.json"), "utf8"),
);

/**
 * Projects the YAML describes, in the authored order, as flat records.
 *
 * `listings` and `sameAs` are merged into one `sameAs` array because the
 * distinction between them is a rendering decision on /projects/ (a listing is
 * a card link, the tail is not) and means nothing to a consumer that renders
 * neither. The order is preserved so the documented install path stays first.
 *
 * @param {Record<string, unknown>} raw - Parsed YAML.
 * @returns {object[]} One record per project.
 */
function toRecords(raw) {
  const items = Array.isArray(raw) ? raw : (raw.projects ?? []);
  return items.map((p) => ({
    id: p.id,
    name: p.name,
    status: p.status,
    schemaType: p.schemaType,
    ...(p.applicationCategory && {
      applicationCategory: p.applicationCategory,
    }),
    ...(p.applicationSubCategory && {
      applicationSubCategory: p.applicationSubCategory,
    }),
    ...(p.kicker && { kicker: p.kicker }),
    language: p.language,
    license: p.license,
    licenseUrl: LICENSE_URLS[p.license] ?? p.license,
    ...(p.operatingSystem && { operatingSystem: p.operatingSystem }),
    repo: p.repo,
    docs: p.docs,
    ...(p.docsEs && { docsEs: p.docsEs }),
    description: p.summary?.en ?? "",
    descriptionEs: p.summary?.es ?? "",
    keywords: (p.topics ?? []).map((t) => t.name),
    sameAs: [
      p.repo,
      ...(p.listings ?? []).map((l) => l.url),
      ...(p.sameAs ?? []),
    ],
    ...(p.endpointSameAs && { endpointSameAs: p.endpointSameAs }),
  }));
}

const raw = parseYaml(fs.readFileSync(SOURCE, "utf8"));
const document = {
  $comment:
    "Generated by scripts/ci/build-projects.mjs from " +
    "src/content/profile/projects.yaml. Do not edit by hand. " +
    "Consumers: filter to the projects you actually publish.",
  generator: "https://github.com/jmrplens/jmrp.io",
  projects: toRecords(raw),
};
const serialized = `${JSON.stringify(document, null, 2)}\n`;

if (process.argv.includes("--check")) {
  const current = fs.existsSync(TARGET) ? fs.readFileSync(TARGET, "utf8") : "";
  if (current !== serialized) {
    console.error(
      "✗ public/identity/projects.json is out of date with its YAML source.\n" +
        "  Regenerate it with: pnpm run projects:build",
    );
    process.exit(1);
  }
  console.log(
    `✓ Canonical project list is in sync with its source (${document.projects.length} projects).`,
  );
  process.exit(0);
}

fs.mkdirSync(path.dirname(TARGET), { recursive: true });
fs.writeFileSync(TARGET, serialized);
console.log(`✓ Wrote ${TARGET} (${document.projects.length} projects)`);
